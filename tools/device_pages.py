"""Write the device pages and the README's summary of them.

usage: python tools/device_pages.py          rewrite every generated table
       python tools/device_pages.py --check  exit 1 if one is out of date

Each brand has a page under docs/devices/ listing every model PairFree knows, with a table
generated from the brand's data: tools/gen_models_table.py for SOUNDPEATS,
tools/gen_soundcore_table.py for Soundcore, tools/gen_samsung_table.py for Samsung,
tools/gen_sony_table.py for Sony and tools/gen_bose_table.py for Bose. The README shows one summary row per brand that
links to its page. Running either generator rewrites all of them, so they never disagree.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
PAGES = ROOT / "docs" / "devices"
START = "<!-- devices-summary:start (generated by tools/device_pages.py; do not edit) -->"
END = "<!-- devices-summary:end -->"

# Links in a page under docs/devices/ start here to reach a file from the repo root.
TO_ROOT = "../../"
HELP = TO_ROOT + "README.md#help-add-your-model"


def brands():
    """The generator for each brand, in the order the README lists them."""
    import gen_bose_table
    import gen_models_table
    import gen_samsung_table
    import gen_sony_table
    import gen_soundcore_table
    return [gen_models_table, gen_soundcore_table, gen_samsung_table, gen_sony_table, gen_bose_table]


def summary():
    """One row per brand: its page, how many models PairFree knows, and which were tried on real earbuds."""
    rows = []
    for brand in brands():
        s = brand.summary()
        page = brand.PAGE.relative_to(ROOT).as_posix()
        rows.append(f"| [{s['brand']}]({page}) | {s['models']} | {', '.join(s['tested']) or '—'} |")
    return "\n".join([
        START,
        "| Brand | Models | Tried on real earbuds |",
        "|-------|--------|-----------------------|",
        *rows,
        END,
    ])


def outputs():
    """Each generated block: the file, its markers and what goes between them (markers included)."""
    out = [(README, START, END, summary())]
    out += [(brand.PAGE, brand.START, brand.END, brand.table()) for brand in brands()]
    return out


def splice(path, start, end, content):
    """The file's text now, and with the block between the markers replaced by content."""
    text = path.read_text(encoding="utf-8")
    if start not in text or end not in text:
        sys.exit(f"{path.relative_to(ROOT).as_posix()} has no markers for {start}")
    return text, text[:text.index(start)] + content + text[text.index(end) + len(end):]


def main(check=None):
    check = "--check" in sys.argv if check is None else check
    stale = []
    for path, start, end, content in outputs():
        old, new = splice(path, start, end, content)
        if new != old:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.write_text(new, encoding="utf-8", newline="\n")
    if check:
        sys.exit(f"out of date: {', '.join(stale)}; run python tools/device_pages.py" if stale else 0)
    print(f"written: {', '.join(stale)}" if stale else "the device pages were already up to date")


if __name__ == "__main__":
    main()
