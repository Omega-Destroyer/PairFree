"""Write the table of 1MORE models, in docs/devices/1more.md.

usage: python tools/gen_1more_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_1more_table.py --check  exit 1 if one is out of date

One row per model in data/1more/devices.json, by the Bluetooth name 1MORE's app matches on. The table says
what 1MORE's product list gives each model. A model counts as tested once it has a report under
data/1more/reports.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "1more.md"
START = "<!-- 1more-table:start (generated by tools/gen_1more_table.py; do not edit) -->"
END = "<!-- 1more-table:end -->"

KINDS = {"earbuds": "Earbuds", "headphones": "Headphones"}
CANCELLING = {"adaptive": "adaptive", "strong": "strong", "mild": "mild", "wind": "wind"}
TRANSPARENCY = {"pass_through": "pass-through", "voice_enhancement": "voice enhancement"}


def load():
    return json.loads((ROOT / "data" / "1more" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def noise(model):
    modes = model["listen_modes"]
    parts = []
    kinds = [CANCELLING[m] for m in CANCELLING if m in modes]
    if kinds:
        parts.append(f"ANC ({', '.join(kinds)})" if len(kinds) > 1 else "ANC")
    if "transparent" in modes:
        extra = [TRANSPARENCY[m] for m in TRANSPARENCY if m in modes]
        parts.append(f"transparency ({', '.join(extra)})" if extra else "transparency")
    return ", ".join(parts) or "—"


def features(model):
    out = []
    if "game" in model["connection"]:
        out.append("game mode")
    if "ldac" in model["connection"]:
        out.append("LDAC")
    for key, name in [("dual_device", "two devices"), ("spatial_audio", "spatial audio"), ("autoplay", "pause when taken out"),
                      ("sleep_detection", "sleep detection"), ("hot_word", "voice commands"), ("ear_return", "hear your own voice"),
                      ("volume_limit", "volume limit")]:
        if model[key]:
            out.append(name)
    if model["touch"] == "each":
        out.append("touch controls (each earbud)")
    elif model["touch"] == "both":
        out.append("touch controls")
    return ", ".join(out) or "—"


def status(model):
    if model["tuya"]:
        return "Not supported (Tuya)"
    return "Tested" if reports(model) else "Not tested"


def rows(devices):
    out = []
    for m in sorted(devices, key=lambda m: m["name"].lower()):
        name = escape(m["name"])
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
        cells = [name, f"<code>{escape(m['model'])}</code>", KINDS[m["kind"]], escape(noise(m)), escape(features(m)), status(m)]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    data = load()
    devices = data["devices"]
    tuya = [m for m in devices if m["tuya"]]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Product", "Type", "Noise control", "Also", "Status"])
    return "\n".join([
        START,
        f"{len(devices)} models by their Bluetooth name, from 1MORE's own product list as 1MORE's app downloads it "
        f"(fetched once on {escape(data['fetched'])}). {len(tuya)} of them go through Tuya's platform instead, which PairFree does not control.",
        "",
        "<b>Tested</b>: tried with PairFree. <b>Not tested</b>: from 1MORE's app and product list alone. "
        f'A device report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for 1MORE: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "1MORE", "models": len(devices), "tested": sorted(m["name"] for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
