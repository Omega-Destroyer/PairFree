"""Write the table of AirPods and Beats models, in docs/devices/apple.md.

usage: python tools/gen_apple_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_apple_table.py --check  exit 1 if one is out of date

One row per model in data/apple/devices.json, AirPods first, then Beats. AirPods name their model
in their information packet; Beats are shown by the name they give. A model counts as tested once it
has a report under data/apple/reports.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "apple.md"
START = "<!-- apple-table:start (generated by tools/gen_apple_table.py; do not edit) -->"
END = "<!-- apple-table:end -->"

KINDS = {"earbuds": "Earbuds", "headphones": "Headphones"}


def load():
    return json.loads((ROOT / "data" / "apple" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def rows(devices):
    out = []
    for m in sorted(devices, key=lambda m: not m["name"].startswith("AirPods")):
        name = escape(m["name"])
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
        numbers = " ".join(f"<code>{escape(n)}</code>" for n in m["model_numbers"]) or "—"
        status = "Tested" if found else ("In doubt: " + escape(m["note"]) if m.get("note") else "Not tested")
        cells = [name, numbers, KINDS[m["kind"]], "Yes" if m.get("adaptive") else "—", status]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    devices = load()["devices"]
    tested = [m for m in devices if reports(m)]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Model numbers", "Type", "Adaptive Audio", "Status"])
    return "\n".join([
        START,
        f"{len(devices)} models: the AirPods LibrePods knows, with the model numbers they report, and the Beats and "
        "AirPods Max MagicPodsCore lists. Each one reports its settings when PairFree connects, and PairFree shows "
        "only those.",
        "",
        f"<b>Tested</b> ({len(tested)}): tried with PairFree. <b>Not tested</b>: from LibrePods and MagicPodsCore. "
        f'A device report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for AirPods and Beats: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "AirPods and Beats", "models": len(devices), "tested": sorted(m["name"] for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
