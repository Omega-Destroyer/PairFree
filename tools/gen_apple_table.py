"""Write the table of AirPods and Beats models, in docs/devices/apple.md.

usage: python tools/gen_apple_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_apple_table.py --check  exit 1 if one is out of date

One row per model in data/apple/devices.json, AirPods first, then Beats. AirPods name their model
in their information packet; Beats are shown by the name they give. A model counts as tested once it
has a report under data/apple/reports.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "apple.md"
START = "<!-- apple-table:start (generated by tools/gen_apple_table.py; do not edit) -->"
END = "<!-- apple-table:end -->"

KINDS = {"earbuds": "Earbuds", "headphones": "Headphones"}


def load():
    return json.loads((ROOT / "data" / "apple" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def rows(devices):
    out = []
    for m in sorted(devices, key=lambda m: not m["name"].startswith("AirPods")):
        name = escape(m["name"])
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
        numbers = " ".join(f"<code>{escape(n)}</code>" for n in m["model_numbers"]) or "—"
        status = "Tested" if found else ("In doubt: " + escape(m["note"]) if m.get("note") else "Not tested")
        cells = [name, numbers, KINDS[m["kind"]], "Yes" if m.get("adaptive") else "—", status]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


NOTE = (
    "<b>Why some of these need a particular Android version.</b> AirPods and AirPods Max take their settings over a classic "
    "Bluetooth L2CAP channel (PSM 0x1001). Android has no public call for a classic L2CAP channel (its public L2CAP calls are for "
    "Bluetooth LE, and the newest one accepts channel numbers 128 to 255 only), so an app can reach it only through "
    "<code>BluetoothSocket</code>'s hidden constructors, and only where the phone's Bluetooth stack accepts the channel. "
    "Until Android 17 the stack refused it except on Pixels with Android 16 QPR3 and on OnePlus, OPPO and realme phones with "
    "Android 16. Google fixed the stack in Android 17, but Android 17 builds can also hide those constructors from apps. Where "
    "they are hidden, PairFree asks Android's runtime, for its own process and for that one class only, to show them, as "
    "LibrePods does (no root, no Xposed); it does so only for AirPods and only after the constructors came back hidden, and the "
    "connection report says whether it was tried. This is a workaround for a restriction, not a public API: a user's AirPods Pro 3 "
    "on a Pixel 8 with Android 17 connected through it (issue #3, PairFree 0.9.1), and a later Android version may close it. "
    "Apple's own Beats app on Android does not use that channel: it talks to the Beats on Apple's chips over an ordinary "
    "Bluetooth serial connection (RFCOMM), which any Android version allows. PairFree now speaks that protocol (B2P) to the Beats "
    "that Apple's app controls that way (Powerbeats Pro and Pro 2, Powerbeats Fit, Fit Pro, Studio Buds and Buds +, Solo Buds, "
    "Solo Pro, Solo 4, Studio Pro): they need no particular Android version. It shows the battery, the listening mode, one-bud "
    "noise cancelling, ear detection, the microphone and the in-case tones, for the models Apple's app lists each for, written from Apple's app and not yet tried on any Beats. The older Beats (Powerbeats3, Solo3, BeatsX, Flex, "
    "Studio3) use another protocol, BCD, over the same serial channel: PairFree shows their noise cancelling switch (and the Flex's auto "
    "answer), also untried; the Beats Pill+ speaker is not covered. See docs/apple/B2P.md."
)


def table():
    devices = load()["devices"]
    tested = [m for m in devices if reports(m)]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Model numbers", "Type", "Adaptive Audio", "Status"])
    return "\n".join([
        START,
        f"{len(devices)} models: the AirPods LibrePods knows, with the model numbers they report, and the Beats and "
        "AirPods Max MagicPodsCore lists. Each one reports its settings when PairFree connects, and PairFree shows "
        "only those.",
        "",
        f"<b>Tested</b> ({len(tested)}): tried with PairFree. <b>Not tested</b>: from LibrePods and MagicPodsCore. "
        f'A device report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        "",
        NOTE,
        END,
    ])


def summary():
    """The README's row for AirPods and Beats: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "AirPods and Beats", "models": len(devices), "tested": sorted(m["name"] for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
