"""Write the table of Bose models, in docs/devices/bose.md.

usage: python tools/gen_bose_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_bose_table.py --check  exit 1 if one is out of date

One row per model in data/bose/devices.json, headphones first, then earbuds and neckbands. A Bose
device reports its product id when PairFree connects, and answers only for the settings it has, so
the table says what each model is, not what it has. A model counts as tested once it has a report
under data/bose/reports; "bosectl" marks the models bosectl was tried on.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "bose.md"
START = "<!-- bose-table:start (generated by tools/gen_bose_table.py; do not edit) -->"
END = "<!-- bose-table:end -->"

KINDS = {"headphones": "Headphones", "earbuds": "Earbuds", "neckband": "Neckband"}
BOSECTL = "https://github.com/aaronsb/bosectl"


def load():
    return json.loads((ROOT / "data" / "bose" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def short(name):
    return name.removeprefix("Bose ")


def rows(devices):
    out = []
    for m in sorted(devices, key=lambda m: list(KINDS).index(m["kind"])):
        name = escape(short(m["name"]))
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
            status = "Tested"
        elif m.get("bosectl"):
            status = "bosectl"
        else:
            status = "Not tested"
        cells = [name, f"<code>{escape(m['product_id'])}</code>", KINDS[m["kind"]], status]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    data = load()
    devices = data["devices"]
    tested = [m for m in devices if reports(m)]
    bosectl = [m for m in devices if m.get("bosectl") and not reports(m)]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Product", "Type", "Status"])
    return "\n".join([
        START,
        f"{len(devices)} models, by the names and product ids Bose's own app gives them. Each device reports its "
        "product id when PairFree connects and answers only for the settings it has, so a Bose model missing here "
        "works the same way.",
        "",
        f"<b>Tested</b> ({len(tested)}): tried with PairFree. <b>bosectl</b> ({len(bosectl)}): "
        f'<a href="{BOSECTL}">bosectl</a> (commit <code>{escape(data["bosectl_commit"][:7])}</code>) was tried on it, '
        "with the messages PairFree sends; its notes do not say which QC35 it was, so both are marked. "
        "<b>Not tested</b>: from Bose's app "
        f'alone. A device report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for Bose: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "Bose", "models": len(devices), "tested": sorted(short(m["name"]) for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
