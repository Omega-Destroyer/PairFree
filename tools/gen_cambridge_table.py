"""Generate the Melomania device page from data/cambridge/devices.json."""
import json
from html import escape

import device_pages

PAGE = device_pages.PAGES / "cambridge.md"
START = "<!-- cambridge-table:start (generated by tools/gen_cambridge_table.py; do not edit) -->"
END = "<!-- cambridge-table:end -->"


def models():
    return json.loads((device_pages.ROOT / "data/cambridge/devices.json").read_text(encoding="utf-8"))["devices"]


def summary():
    return {"brand": "Cambridge Audio", "models": len(models()), "tested": []}


def table():
    rows = []
    for model in models():
        if model.get("connect"):
            features = ("Battery, noise control and its button cycle, equalizer with presets, left/right balance, gaming, mono, sleep, loudness, side tone and spatial audio "
                        "(each where the model has it), wear detection, find alert, touch gestures and their actions, paired devices, voice language, automatic power off, codec choice")
        else:
            features = "Battery, presets and five gain bands, control toggles, language and codec preference"
            if model["ambient"]:
                features += ", ambient sound and level"
        virtual = [p for p in model.get("virtual_tests", []) if (device_pages.ROOT / p).is_file()]
        status = "Not tested"
        if virtual:
            status = f'<a href="{escape(device_pages.TO_ROOT + virtual[0])}">Vendor app tested virtually</a>; no hardware test'
        rows.append(f"<tr><td>{escape(model['name'])}</td><td>{features}</td><td>{status}</td></tr>")
    return "\n".join([START, "<table>", "<tr><th>Model</th><th>Implemented</th><th>Status</th></tr>", *rows, "</table>", END])


if __name__ == "__main__":
    device_pages.main()
