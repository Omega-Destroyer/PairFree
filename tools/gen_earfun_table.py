"""Write the table of EarFun models, in docs/devices/earfun.md.

usage: python tools/gen_earfun_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_earfun_table.py --check  exit 1 if one is out of date

One row per model in data/earfun/devices.json, by its Bluetooth name. The table says what EarFun's app offers
each model that PairFree shows, and which models are on chips whose protocol PairFree does not cover yet. A model
counts as tested once it has a report under data/earfun/reports.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "earfun.md"
START = "<!-- earfun-table:start (generated by tools/gen_earfun_table.py; do not edit) -->"
END = "<!-- earfun-table:end -->"

KINDS = {"earbuds": "Earbuds", "headphones": "Headphones"}
CANCELLING = {"anc": "standard", "anc1": "ANC 1", "anc2": "ANC 2", "adaptive": "adaptive", "wind": "wind",
              "default": "standard", "balance": "balanced", "ear_adaptive": "adapts to your ears",
              "level4": "levels 1 to 4", "level3": None, "level2": None, "level1": None}
AMBIENT = {"total": "full", "natural": "natural"}


def load():
    return json.loads((ROOT / "data" / "earfun" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def noise(model):
    n = model["noise"]
    if not n:
        return "—"
    tops = [m for m in n["values"] if m not in ("off", "ambient")]
    kinds = [CANCELLING[m] for m in tops] if len(tops) > 1 else []
    kinds += [CANCELLING[m] for m in (n.get("cancelling") or {}).get("options", [])]
    kinds = [k for k in dict.fromkeys(kinds) if k]
    parts = [f"ANC ({', '.join(kinds)})" if len(kinds) > 1 else "ANC"]
    if "ambient" in n["values"]:
        extra = [AMBIENT[m] for m in (n.get("ambient") or {}).get("options", []) if m in AMBIENT]
        parts.append(f"ambient ({', '.join(extra)})" if extra else "ambient")
    return ", ".join(parts)


def features(model):
    out = []
    for key, name in [("game", "game mode"), ("multipoint", "two devices"), ("spatial", "spatial audio"), ("in_ear", "pause and answer in the ear"),
                      ("mic", "microphone"), ("prompt_volume", "voice prompt volume"), ("hearing_protection", "volume limit"), ("find", "find the earbuds")]:
        if model[key]:
            out.append(name)
    if model["auto_off"]:
        out.append("auto power-off")
    if model["eq"]:
        out.append(f"{len(model['eq']['hz'])}-band EQ with presets")
    if model["touch"]:
        out.append("touch controls" + (" (can be turned off)" if model["touch"]["disable"] else ""))
    return ", ".join(out) or "—"


def status(model):
    if not model["covered"]:
        return f"Not yet ({escape(model['chip'])})"
    return "Tested" if reports(model) else "Not tested"


def rows(devices):
    out = []
    for m in sorted(devices, key=lambda m: m["name"].lower()):
        name = escape(m["name"])
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
        codes = ", ".join(f"<code>{escape(c)}</code>" for c in m["codes"])
        covered = m["covered"]
        cells = [name, codes, KINDS[m["kind"]], escape(noise(m)) if covered else "—", escape(features(m)) if covered else "—", status(m)]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    devices = load()["devices"]
    later = [m for m in devices if not m["covered"]]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "EarFun's code", "Type", "Noise control", "Also", "Status"])
    return "\n".join([
        START,
        f"{len(devices)} models by their Bluetooth name, from EarFun's own app. {len(later)} of them are on chips whose own protocol "
        "PairFree does not cover yet; PairFree does not list those among the paired earbuds.",
        "",
        "<b>Tested</b>: tried with PairFree. <b>Not tested</b>: from EarFun's app alone. "
        f'A device report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for EarFun: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "EarFun", "models": len(devices), "tested": sorted(m["name"] for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
