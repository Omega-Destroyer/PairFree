"""Generate Huawei's device table from the same profiles that drive the app."""
import json
from html import escape

import device_pages

PAGE = device_pages.PAGES / "huawei.md"
START = "<!-- huawei-table:start (generated by tools/gen_huawei_table.py) -->"
END = "<!-- huawei-table:end -->"


def products():
    return json.loads((device_pages.ROOT / "data/huawei/devices.json").read_text(encoding="utf-8"))["products"]


def summary():
    return {"brand": "Huawei and Honor", "models": len(products()), "tested": []}


def coverage(product):
    features = set(product["features"])
    if "report_only" in features:
        return "Catalogue entry"
    rows = ["Battery"]
    if features & {"anc", "legacy_anc"}:
        rows.append("Noise control")
    if features & {"pinch", "double", "shark_tap", "walrus_tap", "hold", "power_tap", "fiji"}:
        rows.append("Gestures")
    if "studio_touch" in features:
        rows.append("Touch lock")
    if product.get("presets"):
        rows.append("EQ presets")
    if features & {"custom_save", "custom_preview"}:
        rows.append("Custom EQ")
    if features & {"wear", "latency", "multipoint", "language", "quality", "head", "fiji"}:
        rows.append("Device settings")
    return ", ".join(rows)


def table():
    rows = []
    for product in products():
        source = product["source"]
        evidence = "Bundled APK" if source.startswith("apk") and source != "apk_catalogue" else "Catalogue"
        if "openfreebuds" in source or "capture_reference" in source:
            evidence = "Bundled APK and public research" if source.startswith("apk") else "Public research"
        status = "Catalogue only" if "report_only" in product["features"] else "Awaiting PairFree hardware test"
        cells = [product["name"], coverage(product), evidence, status]
        rows.append("<tr>" + "".join(f"<td>{escape(cell)}</td>" for cell in cells) + "</tr>")
    return "\n".join([START, "<table>", "<tr><th>Model</th><th>PairFree controls</th><th>Evidence</th><th>Status</th></tr>", *rows, "</table>", END])


if __name__ == "__main__":
    device_pages.main()
