def slug(text):
    t = text.replace("+", "plus_").replace("-", "minus_")
    return re.sub(r"[^a-z0-9]+", "_", t.lower()).strip("_")


def humanize(name):
    words = [w for w in re.split(r"[_\s]+", name) if w]
    out = []
    for i, w in enumerate(words):
        low = w.lower()
        low2 = re.sub(r"(\d)(db)$", r"\1 dB", low)
        if low in WORDS:
            out.append(WORDS[low])
        elif low2 != low:
            out.append(low2)
        else:
            out.append(w if w.isupper() and len(w) > 1 else low)
    text = " ".join(out)
    return text[:1].upper() + text[1:]


def button_title(name):
    m = re.match(r"^(Music|Call_incoming|Ongoing_call)_context_(left|right)_button_(tap|double_tap|triple_tap)_action$", name)
    if not m:
        return None
    ctx = {"Music": "Music", "Call_incoming": "Incoming call", "Ongoing_call": "In a call"}[m.group(1)]
    gesture = {"tap": "tap", "double_tap": "double tap", "triple_tap": "triple tap"}[m.group(3)]
    return f"{ctx}: {m.group(2)} earbud, {gesture}"


def xml(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace("'", "\\'").replace('"', '\\"')


def build():
    S = json.loads(SETTINGS.read_text(encoding="utf-8"))["settings"]
    titles = {}
    for sid, s in S.items():
        n = s["name"]
        titles[n] = TITLES.get(n) or button_title(n) or humanize(n)
    options = {}
    for s in S.values():
        for o, _ in s["options"]:
            options[o] = OPTIONS.get(o) or humanize(re.sub(r"^(Action|Audio_announcements|Audio_protection_setting|Audio_protection|Tone_setting|Equalizer_mode_for_calls)_", "", o))
    lines = [BEGIN]
    seen = {}
    for n in sorted(titles):
        name = f"jb_title_{slug(n)}"
        if name in seen:
            assert seen[name] == titles[n], (n, titles[n], seen[name])
            continue
        seen[name] = titles[n]
        lines.append(f'    <string name="{name}">{xml(titles[n])}</string>')
    for o in sorted(options):
        name = f"jb_opt_{slug(o)}"
        if name in seen:
            assert seen[name] == options[o], (o, options[o], seen[name])
            continue
        seen[name] = options[o]
        lines.append(f'    <string name="{name}">{xml(options[o])}</string>')
    for k, v in FIXED_OPTIONS.items():
        lines.append(f'    <string name="jb_fixed_{k}">{xml(v)}</string>')
    for g in sorted(GROUPS):
        lines.append(f'    <string name="jb_group_{slug(g)}">{xml(GROUPS[g])}</string>')
    for k, v in FIXED_TITLES.items():
        lines.append(f'    <string name="{k}">{xml(v)}</string>')
    lines.append(END)

    kt = ["// Generated by tools/gen_jabra_strings.py from data/jabra/settings.json. Do not edit.", "package io.github.omegadestroyer.pairfree.ui", "",
          "import io.github.omegadestroyer.pairfree.R", "", "/** The words of Jabra's setting rows: setting id, option name and group to their strings. */", "internal object JabraLabels {",
          "    val TITLE: Map<String, Int> = mapOf("]
    for sid, s in sorted(S.items()):
        kt.append(f'        "{sid}" to R.string.jb_title_{slug(s["name"])},')
    kt += ["    )", "", "    val OPTION: Map<String, Int> = mapOf("]
    for o in sorted(options):
        kt.append(f'        "{o}" to R.string.jb_opt_{slug(o)},')
    kt += ["    )", "", "    val GROUP: Map<String, Int> = mapOf("]
    for g in sorted(GROUPS):
        kt.append(f'        "{g}" to R.string.jb_group_{slug(g)},')
    kt += ["    )", "", "    val FIXED_TITLE: Map<String, Int> = mapOf("]
    for k in sorted(FIXED_TITLES):
        kt.append(f'        "{k}" to R.string.{k},')
    kt += ["    )", "}", ""]
    return "\n".join(lines), "\n".join(kt)


def main():
    section, kt = build()
    text = STRINGS.read_bytes().decode("utf-8")
    nl = "\r\n" if "\r\n" in text else "\n"
    text = text.replace("\r\n", "\n")
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END) + len(END)
        new = text[:a] + section + text[b:]
    else:
        new = text.replace("</resources>", section + "\n</resources>")
    kt_old = LABELS.read_bytes().decode("utf-8").replace("\r\n", "\n") if LABELS.exists() else ""
    if "--check" in sys.argv:
        if new != text or kt != kt_old:
            print("out of date: run python tools/gen_jabra_strings.py")
            sys.exit(1)
        print("up to date")
        return
    STRINGS.write_bytes(new.replace("\n", nl).encode("utf-8"))
    LABELS.write_bytes(kt.replace("\n", nl).encode("utf-8"))
    print(f"wrote {section.count('<string')} strings")


if __name__ == "__main__":
    main()
