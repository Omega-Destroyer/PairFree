"""Generate the Jabra device page's table from data/jabra/devices.json and settings.json."""
import json
from html import escape

import device_pages

PAGE = device_pages.PAGES / "jabra.md"
START = "<!-- jabra-table:start (generated by tools/gen_jabra_table.py; do not edit) -->"
END = "<!-- jabra-table:end -->"

# What each of the vendor's commands is called on the page.
LABELS = {
    "DSP_SIDETONE": "sidetone", "USER_BUTTONS": "button functions", "INACTIVITY_INTERVAL": "automatic switch-off", "AUTO_PAUSE_MUSIC": "pause music when taken off",
    "ON_HEAD_DETECTION": "on-head detection", "HS_VOICE_PROMPTS": "voice prompts", "CURRENT_LANGUAGE": "voice language", "SOUND_MODE": "call sound",
    "MUTE_REMINDER_INTERVAL": "mute reminder", "AUTO_MUTE_CALL_AUDIO": "mute when taken off", "AUTO_ANSWER_CALL": "answer when put on", "BUSYLIGHT": "busy light",
    "VIBRA": "vibration", "WIND_ADAPTIVE": "wind noise reduction", "AUTO_VOLUME_CONTROL": "automatic volume adjustment", "AUTO_HT_FOR_SINGLE_EARBUD": "HearThrough with one earbud",
    "BUTTON_SOUNDS": "button sounds", "AUTO_REJECT_BG_WAITING": "reject a waiting call", "CALL_ID_PROMPT": "announce the caller", "RADIO": "Bluetooth",
}


def data():
    return json.loads((device_pages.ROOT / "data/jabra/devices.json").read_text(encoding="utf-8"))


def settings():
    return json.loads((device_pages.ROOT / "data/jabra/settings.json").read_text(encoding="utf-8"))["settings"]


def models():
    return data()["models"]


def gnp(m):
    return any(v["protocol"] == "gnp" for v in m["variants"])


def summary():
    return {"brand": "Jabra", "models": sum(1 for m in models() if gnp(m)), "tested": []}


def shown(m):
    d, s = data(), settings()
    out = ["battery"]
    snapshots = [x for v in m["variants"] for x in v["snapshots"]]
    profiles = [d["profiles"][x] for x in snapshots]
    ids = [i for p in profiles for i in p["settings"]]
    caps = {c for p in profiles for c in p["caps"]}
    commands = {s[i]["command"] for i in ids if i in s}
    if "ambiencemodes" in caps or "ANC" in commands:
        out.append("noise control")
    elif "HEAR_THROUGH" in commands:
        out.append("HearThrough")
    if "ambiencemodes" in caps:
        out.append("noise levels")
    if "loopmodessupport" in caps:
        out.append("modes on the button")
    if "music_equalizer" in caps:
        out.append("equalizer")
    for command, label in LABELS.items():
        if command in commands:
            out.append(label)
    if "spotifytap" in caps:
        out.append("Spotify one tap")
    if any(c.startswith("spatialsound") for c in caps):
        out.append("spatial sound")
    return ", ".join(dict.fromkeys(out))


def table():
    rows = []
    for m in models():
        if gnp(m):
            text, status = shown(m), "Not tested"
        else:
            text, status = "Not covered yet (Qualcomm's GAIA, not Jabra's own protocol)", "Not covered"
        pids = ", ".join(str(v["pid"]) for v in m["variants"])
        rows.append(f"<tr><td>{escape(m['name'])}</td><td>{m['kind']}</td><td>{pids}</td><td>{escape(text)}</td><td>{status}</td></tr>")
    return "\n".join([START, "<table>", "<tr><th>Model</th><th>Kind</th><th>Product id</th><th>Shown</th><th>Status</th></tr>", *rows, "</table>", END])


if __name__ == "__main__":
    device_pages.main()
