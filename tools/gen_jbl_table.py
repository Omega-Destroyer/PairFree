"""Write the table of JBL models, in docs/devices/jbl.md.

usage: python tools/gen_jbl_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_jbl_table.py --check  exit 1 if one is out of date

One row per model in data/jbl/devices.json, headphones first, then earbuds and glasses, with how
PairFree reaches it and the settings JBL's app shows for it. A model counts as tested once it has a
report under data/jbl/reports; its "tried" names the open-source project that used the same
commands on it.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "jbl.md"
START = "<!-- jbl-table:start (generated by tools/gen_jbl_table.py; do not edit) -->"
END = "<!-- jbl-table:end -->"

KINDS = {"headphones": "Headphones", "earbuds": "Earbuds", "glasses": "Glasses"}
CONNECT = {"BLE": "Bluetooth LE", "BT": "Serial"}
MODES = {"anc": "noise cancelling", "ambient_aware": "Ambient Aware", "talk_thru": "TalkThru"}
EXTRAS = {
    "smart_audio_video": "Smart Audio & Video",
    "voice_prompts": "voice prompts",
    "balance": "balance",
    "voice_aware": "VoiceAware",
    "safe_sound": "SafeSound",
    "spatial": "3D spatial sound",
    "sound_effect": "sound effect",
    "audio_limiter": "audio limiter",
    "speak_to_chat": "speak to chat",
    "hi_res": "Hi-Res audio",
    "find_buds": "Find My Buds",
}
TRIED = {
    "JblTray": "https://github.com/emperorbug46/JblTray",
    "FajkPes": "https://github.com/FajkPes/JBL-Headphones-App",
}


def load():
    return json.loads((ROOT / "data" / "jbl" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def short(name):
    return name.removeprefix("JBL ")


def settings(m):
    """The settings PairFree offers on the model besides the battery, in words."""
    out = [MODES[x] for x in m.get("modes", [])]
    if m.get("auto_off"):
        out.append("auto power-off")
    if m.get("auto_play_pause"):
        out.append("pause when taken off")
    out += [EXTRAS[x] for x in m.get("settings", [])]
    return ", ".join(out) or "battery only"


def rows(devices):
    out = []
    for m in sorted(devices, key=lambda m: list(KINDS).index(m["kind"])):
        name = escape(short(m["name"]))
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
            status = "Tested"
        elif m.get("tried"):
            status = f'<a href="{TRIED[m["tried"]]}">{escape(m["tried"])}</a>'
        else:
            status = "Not tested"
        pids = " ".join(f"<code>{escape(p)}</code>" for p in m["pids"])
        cells = [name, pids, KINDS[m["kind"]], CONNECT[m["connect"]], escape(settings(m)), status]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    data = load()
    devices = data["devices"]
    tested = [m for m in devices if reports(m)]
    tried = [m for m in devices if m.get("tried") and not reports(m)]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Product", "Type", "Connection", "Settings", "Status"])
    return "\n".join([
        START,
        f"{len(devices)} models, by the names and product ids JBL's own app gives them, with the settings it shows "
        "for each. <b>Bluetooth LE</b> models may need PairFree to look for them nearby (see above).",
        "",
        f"<b>Tested</b> ({len(tested)}): tried with PairFree. <b>JblTray</b> or <b>FajkPes</b> ({len(tried)}): an "
        "open-source project used the same commands on it. <b>Not tested</b>: from JBL's app alone. A device report "
        f'from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for JBL: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "JBL", "models": len(devices), "tested": sorted(short(m["name"]) for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
