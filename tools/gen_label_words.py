"""Writes the desktop apps' words for gestures, actions, languages and shutdown times from the Android app's own Labels.kt.

Same method as tools/gen_setting_words.py: android/app/.../ui/Labels.kt names the entry of the strings file for each touch gesture,
action, prompt language and timer; every `R.string.name` becomes the key "name" and `stringResource` becomes `t(...)`.
tools/test_setting_words.py fails while the generated file is out of date.

    python tools/gen_label_words.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "android/app/src/main/kotlin/io/github/omegadestroyer/pairfree/ui/Labels.kt"
TARGET = ROOT / "desktop/shell/src/commonMain/kotlin/LabelWords.kt"


def generate() -> str:
    text = SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n")
    start = text.index("/** Tap, double tap, triple tap or press and hold")
    part = text[start:]
    enums = re.findall(r"^enum class .*$", part, flags=re.M)
    gesture = re.search(r"/\*\* The gesture number.*?\n\n", part, flags=re.S).group(0).strip()
    body = part[part.index("@Composable\nfun gestureName"):]
    body = re.sub(r"^@Composable\n", "", body, flags=re.M)
    body = re.sub(r"R\.string\.(\w+)", r'"\1"', body)
    body = body.replace("stringResource(", "t(")
    body = re.sub(r"^private fun unknownCode", "private fun unknownCode", body, flags=re.M)
    body = "".join(("    " + line if line.strip() else line) for line in body.splitlines(True))
    head = (
        "// Generated by tools/gen_label_words.py from the Android app's ui/Labels.kt. Do not edit.\n"
        "package io.github.omegadestroyer.pairfree.shell\n\n"
        "import io.github.omegadestroyer.pairfree.protocol.Command\n"
        "import io.github.omegadestroyer.pairfree.protocol.CustomKeys\n"
        "import io.github.omegadestroyer.pairfree.protocol.soundcore.TouchPress\n\n"
        + "\n".join(enums) + "\n\n" + gesture + "\n\n"
        "/** The words for touch gestures, actions, prompt languages and timers in one language (the same mapping the Android screens use). */\n"
        "class LabelWords(private val strings: DesktopStrings) {\n"
        "    private fun t(key: String, vararg args: Any?): String = strings.text(key, *args)\n\n"
    )
    return head + body.rstrip() + "\n}\n"


if __name__ == "__main__":
    out = generate()
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.exists() and TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") == out else 1)
    TARGET.write_text(out, encoding="utf-8", newline="\n")
    print("wrote", TARGET.relative_to(ROOT), out.count("\n"), "lines")
