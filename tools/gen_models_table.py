"""Write the table of every SOUNDPEATS model and what is known to work on it, in docs/devices/soundpeats.md.

usage: python tools/gen_models_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_models_table.py --check  exit 1 if one is out of date

One row per model in data/soundpeats/devices.json. A model's features come from its device reports
(the "reports" list): lines in the probe's format, `name  GET  ...  raw=..` or `no reply`,
which tools/probe.py and the app's Copy device report both print. A feature counts when its
read answered, except commands marked per_model in data/soundpeats/commands.json, which also need the
model's "confirmed" list, as in the app. The fit test needs the GAIA feature list line the
app's report adds on Qualcomm models. The equalizer needs the model's "eq" entry.
"""
import json
import re
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "soundpeats.md"
RECORD = TO_ROOT + "README.md#record-from-the-official-app"
START = "<!-- models-table:start (generated by tools/gen_models_table.py; do not edit) -->"
END = "<!-- models-table:end -->"

# The features the app offers, in column order: header and the commands behind it.
FEATURES = [
    ("Battery", ["battery_left", "battery_right", "battery_case"]),
    ("Noise control", ["anc_mode"]),
    ("Transparency levels", ["transparency_level"]),
    ("Game mode", ["game_mode"]),
    ("Two devices", ["multipoint"]),
    ("LDAC", ["ldac"]),
    ("LE Audio", ["le_audio"]),
    ("Gestures", ["custom_keys"]),
    ("Touch off", ["touch_disabled"]),
    ("In-ear detection", ["in_ear_detection"]),
    ("Voice prompts", ["prompt_volume", "voice_language"]),
    ("Auto power-off", ["auto_shutdown"]),
    ("Find earbuds", ["find_left", "find_right"]),
    ("Water drain", ["water_drain"]),
]
FAMILIES = {"QUALCOMM": "Qualcomm", "WUQI": "WUQI", "FOTA": "Bluetrum", "JIELI": "Jieli", "BES": "BES",
            "ACTIONS": "Actions", "SMARTLINK": "Smartlink", "QCY-WUQI": "QCY"}
UNSUPPORTED_FAMILIES = {"QCY-WUQI"}
GAIA_FIT_FEATURE = 0x09

YES, NO = "✅", "—"
LINE = re.compile(r"^([a-z_]+) +([0-9A-F]{4})  +(.*?)\s*$")
GAIA_LINE = re.compile(r"^gaia_features +0001  +((?:[0-9a-fA-F]{2} ?)*)\s*$")


def load(name):
    return json.loads((ROOT / "data" / "soundpeats" / name).read_text(encoding="utf-8"))


def read_reports(paths, commands):
    """Commands that answered and that did not, and the GAIA features (or None), over all reports."""
    answered, silent, gaia = set(), set(), None
    for rel in paths:
        path = ROOT / rel
        if not path.exists():
            continue
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if m := GAIA_LINE.match(line):
                gaia = (gaia or set()) | {int(x, 16) for x in m.group(1).split()}
            elif (m := LINE.match(line)) and m.group(1) in commands:
                if m.group(3) == "no reply":
                    silent.add(m.group(1))
                elif "raw=" in m.group(3):
                    answered.add(m.group(1))
    return answered, silent - answered, gaia


def display_name(model):
    seen, out = set(), []
    for n in model["names"]:
        short = re.sub(r"^(LE-)?SOUNDPEATS ", "", n).strip()
        if short.lower() not in seen:
            seen.add(short.lower())
            out.append(short)
    return ", ".join(out)


def rows(devices, commands):
    out = []
    for m in sorted(devices, key=lambda m: (display_name(m).lower(), m["firmware_code"])):
        answered, _, gaia = read_reports(m.get("reports", []), commands)
        code = escape(m["firmware_code"])
        probe_reports = [r for r in m.get("reports", []) if (ROOT / r).exists()]
        if probe_reports and answered:
            code = f'<a href="{escape(TO_ROOT + probe_reports[0])}">{code}</a>'
        cells = [f"<td>{escape(display_name(m))}</td>", f"<td>{code}</td>",
                 f"<td>{FAMILIES.get(m['family'], escape(m['family']))}</td>"]
        span = len(FEATURES) + 2
        if m["family"] in UNSUPPORTED_FAMILIES:
            cells.append(f'<td colspan="{span}">Not supported: a different protocol (docs/soundpeats/PROTOCOL.md section 10)</td>')
        else:
            if not answered:
                cells.append(f'<td colspan="{span - 1}"><a href="{HELP}">Needs a device report</a></td>')
            else:
                confirmed = set(m.get("confirmed", []))
                for _, ids in FEATURES:
                    ok = any(i in answered and (not commands[i].get("per_model") or i in confirmed) for i in ids)
                    cells.append(f"<td>{YES if ok else NO}</td>")
                if m["family"] != "QUALCOMM":
                    fit = NO
                elif gaia is None:
                    fit = f'<a href="{HELP}">Needs a new report</a>'
                else:
                    fit = YES if GAIA_FIT_FEATURE in gaia else NO
                cells.append(f"<td>{fit}</td>")
            eq = YES if m.get("eq") else f'<a href="{RECORD}">Needs a recording</a>'
            cells.append(f"<td>{eq}</td>")
        out.append("<tr>" + "".join(cells) + "</tr>")
    return out


def table():
    commands = {c["id"]: c for c in load("commands.json")["commands"]}
    devices = load("devices.json")["devices"]
    supported = [m for m in devices if m["family"] not in UNSUPPORTED_FAMILIES]
    reported = sum(1 for m in supported if read_reports(m.get("reports", []), commands)[0])
    with_eq = sum(1 for m in supported if m.get("eq"))
    header = "".join(f"<th>{escape(h)}</th>" for h in
                     ["Model", "Firmware code", "Chip"] + [f for f, _ in FEATURES] + ["Fit test", "Equalizer"])
    return "\n".join([
        START,
        f"{len(supported)} models in the official app's table, {reported} with a device report and "
        f"{with_eq} with their equalizer recorded. Some models have more than one firmware code: "
        "PairFree tells them apart by the code the earbuds report.",
        "",
        f"{YES} works with PairFree on this model. {NO} the model does not have it, or PairFree "
        "does not offer it there. A model without a device report can still be used: PairFree "
        "shows whatever the earbuds answer, but nobody has reported what that is yet.",
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices, commands),
        "</table>",
        END,
    ])


def summary():
    """The README's row for SOUNDPEATS: the models PairFree knows, and those with a device report."""
    commands = {c["id"]: c for c in load("commands.json")["commands"]}
    supported = [m for m in load("devices.json")["devices"] if m["family"] not in UNSUPPORTED_FAMILIES]
    tested = sorted(display_name(m) for m in supported if read_reports(m.get("reports", []), commands)[0])
    return {"brand": "SOUNDPEATS", "models": len(supported), "tested": tested}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
