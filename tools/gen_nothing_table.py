"""Write the table of Nothing and CMF models, in docs/devices/nothing.md.

usage: python tools/gen_nothing_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_nothing_table.py --check  exit 1 if one is out of date

One row per model in data/nothing/devices.json: Nothing's earbuds, then CMF's, then the headphones and
the neckband. The earbuds report their product id when PairFree connects, and the model's entry, read
from Nothing X's own feature table, says what it has; the table lists the main ones. A model counts as
tested once it has a report under data/nothing/reports; "nada" and "nadamas" mark the models those
projects were used with.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "nothing.md"
START = "<!-- nothing-table:start (generated by tools/gen_nothing_table.py; do not edit) -->"
END = "<!-- nothing-table:end -->"

KINDS = {"earbuds": "Earbuds", "headphones": "Headphones", "neckband": "Neckband"}
PROJECTS = {"nada": "https://github.com/chukfinley/nada", "nadamas": "https://github.com/ezvk/nadamas"}
NOISE = {"adaptive": "adaptive", "high": "high", "mid": "mid", "low": "low"}


def load():
    return json.loads((ROOT / "data" / "nothing" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def order(m):
    return (list(KINDS).index(m["kind"]), m["brand"] != "Nothing", m["product_id"])


def newest(model):
    """The features on the newest firmware: the range with no upper end, and of those the latest start."""
    open_ended = [c for c in model["configs"] if "max_firmware" not in c] or model["configs"]
    return max(open_ended, key=lambda c: tuple(int(x) for x in c.get("min_firmware", "*.*.0.0").split(".")[-2:]))


def noise(config):
    """Noise cancelling with its strengths, transparency, or a dash."""
    levels = [v for k, v in NOISE.items() if k in config["anc"]]
    parts = []
    if levels:
        parts.append("ANC (" + ", ".join(levels) + ")" if len(levels) > 1 else "ANC")
    if "transparency" in config["anc"]:
        parts.append("transparency")
    return ", ".join(parts) or "—"


def features(config):
    """What else the model has."""
    out = []
    if config["eq_presets"]:
        out.append("EQ presets")
    if config["bass_boost"]:
        out.append("bass boost")
    if config["spatial_audio"]:
        out.append("spatial audio")
    if config["codecs"]:
        out.append(" and ".join(c.upper() for c in config["codecs"]))
    if config["ear_detection"]:
        out.append("in-ear detection")
    if config["low_latency"]:
        out.append("low lag")
    if any(g["custom"] and g["button"] == 1 for g in config["gestures"]):
        out.append("touch controls")
    return ", ".join(out) or "—"


def rows(devices):
    out = []
    for m in sorted(devices, key=order):
        name = escape(m["name"])
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
            status = "Tested"
        elif m.get("tried"):
            status = m["tried"]
        else:
            status = "Not tested"
        config = newest(m)
        cells = [name, f"<code>{escape(m['product_id'])}</code>", KINDS[m["kind"]], escape(noise(config)), escape(features(config)), status]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    devices = load()["devices"]
    tested = [m for m in devices if reports(m)]
    tried = [m for m in devices if m.get("tried") and not reports(m)]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Product", "Type", "Noise control", "Also", "Status"])
    links = " and ".join(f'<a href="{url}">{name}</a>' for name, url in PROJECTS.items())
    return "\n".join([
        START,
        f"{len(devices)} models, by the product ids they report. Noise control and the rest come from the feature table "
        "Nothing X bundles, for the newest firmware it lists; a model that reports a product id missing here gets "
        "whatever it answers for.",
        "",
        f"<b>Tested</b> ({len(tested)}): tried with PairFree. <b>nada</b>, <b>nadamas</b> ({len(tried)}): {links} "
        "were used with one, sending the messages PairFree sends. <b>Not tested</b>: from Nothing X alone. A device "
        f'report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for Nothing: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "Nothing and CMF", "models": len(devices), "tested": sorted(m["name"] for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
