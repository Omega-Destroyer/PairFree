"""Generate the OnePlus and OPPO device page's table from data/oneplus/devices.json (tools/import_heymelody_catalog.py)."""
import json
from html import escape

import device_pages

PAGE = device_pages.PAGES / "oneplus.md"
START = "<!-- oneplus-table:start (generated by tools/gen_oneplus_table.py; do not edit) -->"
END = "<!-- oneplus-table:end -->"
VIRTUAL = {"062014": "data/oneplus/emulator_vectors.json"}


def models():
    """The models HeyMelody lists, without the ones its catalog hides from its own list."""
    return [m for m in json.loads((device_pages.ROOT / "data/oneplus/devices.json").read_text(encoding="utf-8"))["devices"] if not m["hidden"]]


def summary():
    return {"brand": "OnePlus and OPPO", "models": len(models()), "tested": []}


def features(m):
    out = ["battery"]
    types = {n["type"] for n in m.get("noise", [])}
    modes = [label for key, label in (("off", "off"), ("noise_cancelling", "noise cancelling"), ("transparency", "transparency")) if key in types]
    if modes:
        out.append("noise control: " + ", ".join(modes))
    if m.get("eq"):
        out.append(f"{len(m['eq']['presets'])} equalizer presets")
    if m.get("features", {}).get("gameMode") == 1:
        out.append("game mode")
    return "; ".join(out)


def table():
    rows = []
    for m in models():
        status = "Not tested"
        if m["id"] in VIRTUAL:
            status = f'<a href="{escape(device_pages.TO_ROOT + VIRTUAL[m["id"]])}">Vendor app and PairFree tested virtually</a>; no hardware test'
        rows.append(f"<tr><td>{escape(m['name'])}</td><td><code>{m['id']}</code></td><td>{escape(features(m))}</td><td>{status}</td></tr>")
    return "\n".join([START, "<table>", "<tr><th>Model</th><th>Product id</th><th>Implemented</th><th>Status</th></tr>", *rows, "</table>", END])


if __name__ == "__main__":
    device_pages.main()
