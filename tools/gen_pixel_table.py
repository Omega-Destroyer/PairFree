"""Write the table of Google Pixel Buds models, in docs/devices/pixel.md.

usage: python tools/gen_pixel_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_pixel_table.py --check  exit 1 if one is out of date

One row per model in data/pixel/devices.json, by name (the app gives two device types the Pixel Buds Pro's name):
how PairFree reaches it, its noise control and what else it has, from the settings message its family takes
(data/pixel/commands.json). The earbuds report their device type when PairFree connects and answer only for the
settings they have. A model counts as tested once it has a report under data/pixel/reports.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "pixel.md"
START = "<!-- pixel-table:start (generated by tools/gen_pixel_table.py; do not edit) -->"
END = "<!-- pixel-table:end -->"

TRANSPORTS = {"maestro": "Maestro", "tlv": "plain frames"}

# What each settings message offers, as the rows PairFree shows (PixelSession).
ALSO = {
    "allegro": "5-band EQ and Google's presets, balance, mono, volume EQ, conversation detection, press and hold per earbud, "
               "the modes it cycles, in-ear detection, multipoint, case sounds",
    "presto": "bass boost, Adaptive Sound, attention alerts, in-ear detection, sharing detection, touch controls on or off",
    "stretto": "bass boost and its level, loudness compensation, Adaptive Sound, in-ear detection, touch controls on or off",
}


def load():
    return json.loads((ROOT / "data" / "pixel" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def models(devices):
    """The models by name, in the order the table lists them, each with every device type that carries the name."""
    out = {}
    for d in devices:
        out.setdefault(d["name"], []).append(d)
    return out


def noise(model):
    if model["family"] != "allegro":
        return "—"
    return "ANC, adaptive, transparency" if model["adaptive"] else "ANC, transparency"


def rows(devices):
    out = []
    for name, group in models(devices).items():
        m = group[0]
        found = [r for d in group for r in reports(d)]
        label = escape(name)
        if found:
            label = f'<a href="{escape(TO_ROOT + found[0])}">{label}</a>'
        types = ", ".join(str(d["device_type"]) for d in group)
        cells = [label, f"<code>{types}</code>", TRANSPORTS[m["transport"]], escape(noise(m)), escape(ALSO[m["family"]]), "Tested" if found else "Not tested"]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    devices = load()["devices"]
    named = models(devices)
    tested = [n for n, g in named.items() if any(reports(d) for d in g)]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Device type", "Connection", "Noise control", "Also", "Status"])
    return "\n".join([
        START,
        f"{len(named)} models, by the device type they report. What each has comes from Google's Pixel Buds app; the "
        "earbuds answer only for the settings they have, so a row lists the most a model can show.",
        "",
        f"<b>Tested</b> ({len(tested)}): tried with PairFree. <b>Not tested</b>: from Google's app alone. A device "
        f'report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for Pixel Buds: the models PairFree knows, and those tried on real earbuds."""
    named = models(load()["devices"])
    return {"brand": "Google Pixel Buds", "models": len(named), "tested": sorted(n for n, g in named.items() if any(reports(d) for d in g))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
