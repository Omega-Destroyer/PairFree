"""Write the table of QCY models, in docs/devices/qcy.md.

usage: python tools/gen_qcy_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_qcy_table.py --check  exit 1 if one is out of date

One row per model in data/qcy/devices.json, by name. QCY earbuds advertise a vendor id that names the
model, and several vendor ids share a name (one per chip). The table says what each model's control panel
offers and whether PairFree speaks its protocol yet: QCY's own, or JieLi's, which is still to come. A model
counts as tested once it has a report under data/qcy/reports.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "qcy.md"
START = "<!-- qcy-table:start (generated by tools/gen_qcy_table.py; do not edit) -->"
END = "<!-- qcy-table:end -->"

KINDS = {"earbuds": "Earbuds", "headphones": "Headphones"}
CHIPS = {"qualcomm": "Qualcomm", "wuqi": "WUQI", "jieli": "JieLi", "zr": "ZR", "rd": "RD", "realtek": "Realtek", "bes": "BES"}
QUICKY = "https://github.com/hui1601/Quicky"


def load():
    return json.loads((ROOT / "data" / "qcy" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def code(model):
    return f"{model['vendor_id']:04X}"


def noise(model):
    modes = {m["mode"]: m for m in model.get("anc", [])}
    parts = []
    if "cancelling" in modes:
        scenes = modes["cancelling"].get("scenes", [])
        parts.append(f"ANC ({len(scenes)} scenes)" if len(scenes) > 1 else "ANC")
    if "transparency" in modes:
        t = modes["transparency"]
        levels = int(t["to"], 16) - int(t["from"], 16) + 1
        parts.append(f"transparency ({levels} levels)" if levels > 1 else "transparency")
    return ", ".join(parts) or "—"


NAMES = {"game_mode": "game mode", "sleep_mode": "sleep mode", "in_ear": "in-ear detection", "ldac": "LDAC", "multipoint": "two devices",
         "wind_detection": "wind detection", "spatial_audio": "spatial audio", "dynamic_eq": "dynamic EQ", "adaptive_volume": "adaptive volume", "led": "status light"}


def features(model):
    out = [NAMES[s["setting"]] for s in model.get("settings", [])]
    if model.get("balance"):
        out.append("balance")
    if model.get("touch") and model["protocol"] == "qcy":
        out.append("touch controls")
    return ", ".join(out) or "—"


def status(model):
    if reports(model):
        return "Tested"
    return "Not tested" if model["protocol"] == "qcy" else "Not yet (JieLi)"


def rows(devices):
    out = []
    for m in sorted(devices, key=lambda m: (m["protocol"] != "qcy", m["name"].lower(), m["vendor_id"])):
        name = escape(m["name"])
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
        chip = CHIPS.get(m["family"], "Other")
        cells = [name, f"<code>{code(m)}</code>", chip, KINDS[m["kind"]], escape(noise(m)), escape(features(m)), status(m)]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    data = load()
    devices = data["devices"]
    supported = [m for m in devices if m["protocol"] == "qcy"]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Vendor id", "Chip", "Type", "Noise control", "Also", "Status"])
    return "\n".join([
        START,
        f"{len(devices)} models by the vendor id they advertise, {len(supported)} of them on QCY's own protocol, which PairFree "
        f"speaks. The rest use JieLi's protocol, which PairFree is still adding. From QCY's product list as "
        f'<a href="{QUICKY}">Quicky</a> (commit <code>{escape(data["quicky_commit"][:7])}</code>) recorded it.',
        "",
        "<b>Tested</b>: tried with PairFree. <b>Not tested</b>: from QCY's app and product list alone. "
        f'A device report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for QCY: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "QCY", "models": len(devices), "tested": sorted(m["name"] for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
