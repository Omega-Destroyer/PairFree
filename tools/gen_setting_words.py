"""Writes the desktop apps' words for the brands' setting rows from the Android app's own mapping.

android/app/.../ui/SettingRows.kt holds, after its composables, the functions that say which entry of the strings file names each setting
row, option, level and note (`groupTitle`, `settingTitle`, `optionLabel` and the rest). The desktop apps need the same mapping, and a
hand-kept copy of 1,500 lines would drift, so this tool makes it from the Android file: every `R.string.name` becomes the key "name"
and `stringResource` / `getString` become `t(...)`, the lookup of the desktop's text table. Run it after changing those functions;
tools/test_setting_words.py fails while the generated file is out of date.

    python tools/gen_setting_words.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "android/app/src/main/kotlin/io/github/omegadestroyer/pairfree/ui/SettingRows.kt"
TARGET = ROOT / "desktop/shell/src/commonMain/kotlin/SettingWords.kt"


def generate() -> str:
    text = SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n")
    start = text.index("@Composable\nprivate fun groupTitle")
    body = text[start:]
    body = re.sub(r"^@Composable\n", "", body, flags=re.M)
    body = re.sub(r"R\.string\.(\w+)", r'"\1"', body)
    body = body.replace("LocalContext.current.optionLabel(", "optionLabel(")
    body = body.replace("internal fun Context.optionLabel(", "fun optionLabel(")
    body = body.replace("stringResource(", "t(").replace("getString(", "t(")
    body = body.replace("private const val", "private val")
    body = re.sub(r"(private fun action(?:Start|Stop)\(key: String\)): Int", r"\1: String", body)
    body = re.sub(r"^private fun (groupTitle|groupNote|settingTitle|settingNote|levelName|actionStart|actionStop)\(", r"fun " + chr(92) + "1(", body, flags=re.M)
    body = body.replace(", as a [Context] function so the home screen widget says the same. ", ". ")
    body = re.sub(r"^private fun optionName\(.*\n", "", body, flags=re.M)
    # members of a class: indent by four spaces
    body = "".join(("    " + line if line.strip() else line) for line in body.splitlines(True))
    sides = re.search(r"^private val TOUCH_SIDES = .*$", text, flags=re.M).group(0)
    head = (
        "// Generated by tools/gen_setting_words.py from the Android app's ui/SettingRows.kt. Do not edit.\n"
        "package io.github.omegadestroyer.pairfree.shell\n\n"
        "/**\n"
        " * The words for the brands' setting rows in one language: which entry of the strings file names each group, row, option, level\n"
        " * and note (the same mapping the Android screens use), looked up in [strings].\n"
        " */\n"
        "class SettingWords(private val strings: DesktopStrings) {\n"
        "    private fun t(key: String, vararg args: Any?): String = strings.text(key, *args)\n\n"
        "    /** Android's `signed()` keeps a sign before its number in right-to-left languages; the desktop does that where it mirrors (docs/DESKTOP.md). */\n"
        "    private fun signed(text: String): String = text\n\n"
        "    " + sides + "\n\n"
    )
    return head + body.rstrip() + "\n}\n"


if __name__ == "__main__":
    out = generate()
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.exists() and TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") == out else 1)
    TARGET.write_text(out, encoding="utf-8", newline="\n")
    print("wrote", TARGET.relative_to(ROOT), out.count("\n"), "lines")
