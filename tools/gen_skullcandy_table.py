"""Generate the Skullcandy device page's table from data/skullcandy/devices.json and the rules in tools/gen_skullcandy_status.py."""
import json
from html import escape

import device_pages
import gen_skullcandy_status as status

PAGE = device_pages.PAGES / "skullcandy.md"
START = "<!-- skullcandy-table:start (generated by tools/gen_skullcandy_table.py; do not edit) -->"
END = "<!-- skullcandy-table:end -->"


def products():
    return json.loads((device_pages.ROOT / "data/skullcandy/devices.json").read_text(encoding="utf-8"))["products"]


def summary():
    return {"brand": "Skullcandy", "models": len(products()), "tested": []}


def kind(p):
    """As SkullcandyNames.kt tells them: the Session and Terrain speakers, headphones by the lines' names, the rest earbuds."""
    if p["name"].startswith(("Session ", "Terrain")):
        return "Speaker"
    if p["name"].lower().startswith(("crusher", "hesh", "aviator", "riff", "plyr", "slyr", "icon", "venue", "cassette")):
        return "Headphones"
    return "Earbuds"


def table():
    modes = json.loads((device_pages.ROOT / "data/skullcandy/eq_modes.json").read_text(encoding="utf-8"))["modes"]
    rows = []
    for p in products():
        shown = ", ".join(status.rows(p, modes)) if status.session(p) or p["chip"] == "qualcomm" else ""
        state = "Not tested" if shown else "Found only: no settings yet" if kind(p) != "Speaker" else "Found only (speakers are held back)"
        rows.append(f"<tr><td>{escape(p['name'])}</td><td>{kind(p)}</td><td>{p['id']}</td><td>{escape(shown)}</td><td>{state}</td></tr>")
    return "\n".join([START, "<table>", "<tr><th>Model</th><th>Kind</th><th>Product id</th><th>Shown</th><th>Status</th></tr>", *rows, "</table>", END])


if __name__ == "__main__":
    device_pages.main()
