"""Write the table of Sony models, in docs/devices/sony.md.

usage: python tools/gen_sony_table.py          rewrite it, and every other device table (tools/device_pages.py)
       python tools/gen_sony_table.py --check  exit 1 if one is out of date

One row per model in data/sony/devices.json, headphones first, then earbuds and neckbands. Sony's
earbuds list the functions they have when PairFree connects (data/sony/functions.json), so the table
does not say what each model has; it says what the model is, which table set it answered with in
Gadgetbridge's notes, and where its name comes from. A model counts as tested once it has a report
under data/sony/reports.
"""
import json
from html import escape
from pathlib import Path

import device_pages
from device_pages import HELP, TO_ROOT

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "devices" / "sony.md"
START = "<!-- sony-table:start (generated by tools/gen_sony_table.py; do not edit) -->"
END = "<!-- sony-table:end -->"

NO = "—"
KINDS = {"headphones": "Headphones", "earbuds": "Earbuds", "neckband": "Neckband"}
ORDER = list(KINDS)
SOURCES = {"gadgetbridge": "Gadgetbridge", "sony_app": "Sony's app"}
GADGETBRIDGE = "https://codeberg.org/Freeyourgadget/Gadgetbridge"


def load():
    return json.loads((ROOT / "data" / "sony" / "devices.json").read_text(encoding="utf-8"))


def reports(model):
    return [r for r in model.get("reports", []) if (ROOT / r).exists()]


def rows(devices):
    out = []
    for m in sorted(devices, key=lambda m: ORDER.index(m["kind"])):
        name = escape(m["name"])
        found = reports(m)
        if found:
            name = f'<a href="{escape(TO_ROOT + found[0])}">{name}</a>'
        status = "Tested" if found else "Not tested"
        table_set = str(m["table_set"]) if m.get("table_set") else NO
        cells = [name, KINDS[m["kind"]], table_set, status, SOURCES[m["source"]]]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    data = load()
    devices = data["devices"]
    tested = [m for m in devices if reports(m)]
    header = "".join(f"<th>{h}</th>" for h in ["Model", "Type", "Table set", "Status", "Name from"])
    return "\n".join([
        START,
        f"{len(devices)} models. Sony's earbuds and headphones say themselves what they have when PairFree connects, "
        "so every model gets what it lists, and a model missing here works the same once the phone shows Sony's "
        "service for it. <b>Table set</b> is the one the model answered with in "
        f'<a href="{GADGETBRIDGE}">Gadgetbridge</a>\'s notes (commit <code>{escape(data["gadgetbridge_commit"][:7])}</code>); '
        "PairFree reads it from the earbuds either way.",
        "",
        f"<b>Tested</b> ({len(tested)}): tried with PairFree. <b>Not tested</b>: from Sony's app and Gadgetbridge "
        f'alone. A device report from any model helps (<a href="{HELP}">Help add your model</a>).',
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices),
        "</table>",
        END,
    ])


def summary():
    """The README's row for Sony: the models PairFree knows, and those tried on real earbuds."""
    devices = load()["devices"]
    return {"brand": "Sony", "models": len(devices), "tested": sorted(m["name"] for m in devices if reports(m))}


def main():
    device_pages.main()


if __name__ == "__main__":
    main()
