"""Write the README's table of Soundcore (Anker) models.

usage: python tools/gen_soundcore_table.py          rewrite the table in README.md
       python tools/gen_soundcore_table.py --check  exit 1 if README.md is out of date

One row per model in data/soundcore/devices.json. What a model has comes from OpenSCQ30, whose
source lists the features it implements for each model (tools/import_openscq30.py), plus what
SoundPeter confirmed on the earbuds (extra_features). A model counts as tested once it has a
recording under data/soundcore/reports, and as checked when its state layout reads the replies
in OpenSCQ30's tests (openscq30_states in data/soundcore/test_vectors.json).
"""
import json
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START = "<!-- soundcore-table:start (generated by tools/gen_soundcore_table.py; do not edit) -->"
END = "<!-- soundcore-table:end -->"

YES, NO = "✅", "—"


def has(features, *names, suffix=None, contains=None):
    return any(f in names or (suffix and f.endswith(suffix)) or (contains and contains in f) for f in features)


# Column header and the test on a model's features (OpenSCQ30's module names plus extra_features).
COLUMNS = [
    ("Noise control", lambda f: has(f, "sound_modes", "d1301_noise_canceling", suffix="_sound_modes")),
    ("Equalizer", lambda f: has(f, contains="equalizer")),
    ("HearID", lambda f: has(f, contains="hear_id")),
    ("Touch controls", lambda f: has(f, "button_configuration", "disable_all_buttons", "d1301_tap_controls_disabled",
                                     suffix="_button_configuration")),
    ("Two devices", lambda f: has(f, "dual_connections")),
    ("LDAC", lambda f: has(f, "ldac")),
    ("Game mode", lambda f: has(f, "gaming_mode", suffix="_gaming_mode")),
    ("3D / spatial", lambda f: has(f, "surround_sound", "a3955_immersive_experience", "a3062_dolby_audio",
                                   suffix="_spatial_audio")),
    ("Wear detection", lambda f: has(f, "wearing_detection")),
    ("Touch tone", lambda f: has(f, "touch_tone")),
    ("Auto power-off", lambda f: has(f, "auto_power_off", "a3116_auto_power_off")),
]


def load():
    return json.loads((ROOT / "data" / "soundcore" / "devices.json").read_text(encoding="utf-8"))


def checked_models():
    """Models with at least one state reply from OpenSCQ30's tests, which the Gradle tests read with the model's layout."""
    vectors = json.loads((ROOT / "data" / "soundcore" / "test_vectors.json").read_text(encoding="utf-8"))
    return {c["model"] for c in vectors.get("openscq30_states", [])}


def features(model):
    return model["openscq30"]["features"] + model.get("extra_features", [])


def battery(f):
    if has(f, contains="dual_battery"):
        return "Each earbud, case" if has(f, contains="case_battery") else "Each earbud"
    return "One" if has(f, contains="battery") else NO


EQ_STATUS = {"hardware": "Tested", "openscq30_tests": "Checked"}


def cell(model, title, has):
    """A feature cell. The equalizer also says how far its write is confirmed (devices.json eq.checked)."""
    if not has:
        return NO
    if title == "Equalizer":
        return f"{YES} " + EQ_STATUS.get(model.get("eq", {}).get("checked"), "Not tested")
    return YES


def rows(devices, checked=frozenset()):
    out = []
    for m in sorted(devices, key=lambda m: (m["names"][0].lower(), m["model"])):
        f = features(m)
        name = escape(", ".join(n.removeprefix("Soundcore ") for n in m["names"]))
        reports = [r for r in m.get("reports", []) if (ROOT / r).exists()]
        code = escape(m["model"])
        if reports:
            code = f'<a href="{escape(reports[0])}">{code}</a>'
            status = "Tested"
        elif m["model"] in checked:
            status = "Checked"
        else:
            status = "Not tested"
        cells = [name, code, status, battery(f)] + [cell(m, title, test(f)) for title, test in COLUMNS]
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    return out


def table():
    data = load()
    devices = data["devices"]
    src = data["source"]
    tested = sum(1 for m in devices if m.get("reports"))
    checked = checked_models()
    header = "".join(f"<th>{escape(h)}</th>" for h in ["Model", "Number", "Status", "Battery"] + [c for c, _ in COLUMNS])
    return "\n".join([
        START,
        f"{len(devices)} models. What each model has, and where each setting sits in its replies, comes from "
        f'<a href="{escape(src["url"])}">OpenSCQ30</a> (commit <code>{escape(src["commit"][:7])}</code>, '
        f"{escape(src['date'])}), the open-source Soundcore app by {escape(src['author'])}, plus what SoundPeter "
        "confirmed on the earbuds.",
        "",
        f"<b>Tested</b> ({tested}): tried on the earbuds with SoundPeter. "
        f"<b>Checked</b> ({len(checked - {m['model'] for m in devices if m.get('reports')})}): SoundPeter reads "
        "every reply from the model that OpenSCQ30's tests hold, most of them from its users' bug reports. "
        "<b>Not tested</b>: read from OpenSCQ30's code alone. A device report from one of these helps "
        "(Help add your model, below).",
        "",
        f"{YES} the model has it. {NO} it does not, as far as OpenSCQ30 knows. SoundPeter shows battery, noise "
        "control, two devices, LDAC and game mode on every model that has them, and the equalizer where its "
        "column says Tested (recorded from the Soundcore app) or Checked (OpenSCQ30's tests hold the exact "
        "packet); the other columns are not in SoundPeter yet.",
        "",
        "<table>",
        f"<tr>{header}</tr>",
        *rows(devices, checked),
        "</table>",
        END,
    ])


def main():
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit("README.md has no soundcore-table markers")
    new = text[:text.index(START)] + table() + text[text.index(END) + len(END):]
    if "--check" in sys.argv:
        sys.exit(0 if new == text else "README.md Soundcore table is out of date: run python tools/gen_soundcore_table.py")
    README.write_text(new, encoding="utf-8", newline="\n")
    print("README.md Soundcore table written")


if __name__ == "__main__":
    main()
