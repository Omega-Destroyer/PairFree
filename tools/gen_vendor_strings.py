#!/usr/bin/env python3
"""Puts every EQ preset name the app can show into the language file, and writes the table the app looks them up in.

The names come from the app itself: `gradlew :app:testDebugUnitTest` (VendorNamesTest) gathers them from the same
adapters the Sound tab uses and writes `android/app/build/vendor-names.tsv` (kind, name, brands). This tool turns that
list into

  * two generated sections of `android/app/src/main/res/values/strings.xml`, between the BEGIN and END markers: the names
    PairFree gives the vendors' presets (`preset_name_*`), and the vendors' own wording (`vendor_*`), which a translator may
    translate or leave out;
  * `android/app/src/main/kotlin/.../ui/VendorNames.kt`, the English name of each with its entry.

Run it after adding a brand, a model or a preset:

    python tools/gen_vendor_strings.py [path/to/vendor-names.tsv]

The list is looked for in the repo's build folder, then in the E: mirror's (CLAUDE.md, Android notes).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STRINGS = ROOT / "android/app/src/main/res/values/strings.xml"
KOTLIN = ROOT / "android/app/src/main/kotlin/io/github/omegadestroyer/pairfree/ui/VendorNames.kt"
LISTS = [ROOT / "android/app/build/vendor-names.tsv", Path("E:/Builds/PairFree/android/app/build/vendor-names.tsv")]

BEGIN = "    <!-- BEGIN EQ PRESET NAMES: generated by tools/gen_vendor_strings.py. In this English file, do not edit by hand. -->"
END = "    <!-- END EQ PRESET NAMES -->"
OWN_NOTE = "    <!-- Names PairFree gives the vendors' presets. Translate these. -->"
VENDOR_NOTE = (
    "    <!-- VENDOR WORDING: EQ preset names as the vendor's own app or table words them, by vendor. Translate them or\n"
    "         leave them out: an entry a translation leaves out shows this English wording. -->"
)


def slug(name):
    s = re.sub(r"[^a-z0-9]+", "_", name.lower().replace("&", " and ")).strip("_")
    return s or "name"


def keys(entries):
    """A resource key for each (kind, name), stable as long as the list is: own names first, then by name."""
    taken, out = set(), {}
    for kind, name in sorted(entries, key=lambda e: (e[0] != "own", e[1])):
        base = ("preset_name_" if kind == "own" else "vendor_") + slug(name)
        key, n = base, 1
        while key in taken:
            n += 1
            key = f"{base}_{n}"
        taken.add(key)
        out[name] = key
    return out


def xml_text(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\\", "\\\\")
    s = s.replace("'", "\\'").replace('"', '\\"')
    return "\\" + s if s[:1] in "@?" else s


def kotlin_text(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def read_list(path):
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            kind, name, brands = line.split("\t")
            rows.append((kind, name, brands))
    return rows


def section(rows, key):
    out = [BEGIN, OWN_NOTE]
    for kind, name, brands in sorted(rows, key=lambda r: r[1]):
        if kind == "own":
            out.append(f'    <string name="{key[name]}">{xml_text(name)}</string>')
    out += ["", VENDOR_NOTE]
    groups = {}
    for kind, name, brands in rows:
        if kind == "vendor":
            groups.setdefault(brands, []).append(name)
    for brands in sorted(groups):
        out.append(f"    <!-- {brands} -->")
        for name in sorted(groups[brands]):
            out.append(f'    <string name="{key[name]}">{xml_text(name)}</string>')
    out.append(END)
    return "\n".join(out)


def kotlin(rows, key):
    lines = [
        "package io.github.omegadestroyer.pairfree.ui",
        "",
        "import io.github.omegadestroyer.pairfree.R",
        "",
        "// Generated by tools/gen_vendor_strings.py. Do not edit by hand.",
        "",
        "/**",
        " * Every EQ preset name the app can show, by its English wording, with its entry in the language file: the names PairFree",
        " * gives the vendors' presets (`preset_name_*`) and the vendors' own wording (`vendor_*`). The English wording stays the",
        " * preset's name inside the app; this is only how it is shown ([presetLabel]).",
        " */",
        "internal object VendorNames {",
        "    val ID: Map<String, Int> = mapOf(",
    ]
    for _, name, _ in sorted(rows, key=lambda r: r[1]):
        lines.append(f'        "{kotlin_text(name)}" to R.string.{key[name]},')
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def write(path, text):
    """Writes [text] with the line endings the file has, or the checkout's for a new file."""
    old = path.read_bytes().decode("utf-8") if path.exists() else ""
    crlf = "\r\n" in old if old else "\r\n" in STRINGS.read_bytes().decode("utf-8")
    text = text.replace("\r\n", "\n")
    path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else next((p for p in LISTS if p.exists()), None)
    if source is None or not source.exists():
        sys.exit("No vendor-names.tsv: run gradlew :app:testDebugUnitTest first (it writes android/app/build/vendor-names.tsv).")
    rows = read_list(source)
    key = keys([(kind, name) for kind, name, _ in rows])
    xml = STRINGS.read_bytes().decode("utf-8").replace("\r\n", "\n")
    block = section(rows, key)
    if BEGIN in xml and END in xml:
        xml = xml[: xml.index(BEGIN)] + block + xml[xml.index(END) + len(END):]
    else:
        xml = xml.replace("</resources>", "\n" + block + "\n</resources>")
    write(STRINGS, xml)
    write(KOTLIN, kotlin(rows, key))
    print(f"{sum(1 for r in rows if r[0] == 'own')} names of PairFree's own and {sum(1 for r in rows if r[0] == 'vendor')} of the vendors' written from {source}")


if __name__ == "__main__":
    main()
